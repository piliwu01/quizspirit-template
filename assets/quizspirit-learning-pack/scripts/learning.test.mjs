import assert from 'node:assert/strict';
import {readProgress,recordAnswer,summarize} from '../src/learning.js';
const bank={bankId:'a',questions:[{id:'1',unit:'敘事句',status:'active'},{id:'2',unit:'表態句',status:'active'}]};
let records=recordAnswer({},'a:1',false);
assert.equal(summarize(bank,records).wrong,1);
records=recordAnswer(records,'a:1',true);
assert.equal(summarize(bank,records).mastered,1);
assert.equal(summarize(bank,records).first,0);
records=recordAnswer(records,'a:1',false);
assert.equal(summarize(bank,records).wrong,1);
assert.equal(records['a:1'].attempts,3);
records=recordAnswer(records,'b:1',true);
assert.equal(summarize(bank,records).attempted,1);
const data={version:1,records,player:{id:25,name:'Zappip',type:'electric'},captured:[{id:25,name:'Zappip',type:'electric'}],streak:4};
assert.deepEqual(readProgress({getItem:()=>JSON.stringify(data)}),data.version && {records,player:data.player,captured:data.captured,streak:4});
assert.deepEqual(readProgress({getItem:()=>'{bad'}),{});
assert.deepEqual(readProgress({getItem:()=>{throw Error('blocked')}}),{});
assert.deepEqual(readProgress({getItem:()=>JSON.stringify({version:1,records:{bad:{attempts:-1}},captured:[{}]})}).records,{});
console.log('PASS: wrong → mastered → wrong, first-answer retention, bank isolation, reload, corrupted/blocked storage');
